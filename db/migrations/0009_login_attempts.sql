-- 0009_login_attempts.sql — límite de intentos de login (extensión posterior).
--
-- No guarda correos ni IPs en claro: `attempt_key` es el sha256 de
-- `email:<normalizado>` o `ip:<origen>`. Así el contador sirve para frenar
-- fuerza bruta sin añadir una tabla de PII innecesaria.
--
-- El límite se aplica en `auth/loginLimiter.ts` con una ventana móvil. Es una
-- defensa contra fuerza bruta; la inyección SQL ya está cubierta por consultas
-- parametrizadas (`$1`) en todo el proyecto.
CREATE TABLE login_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_key  text NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX login_attempts_key_time_idx
  ON login_attempts (attempt_key, attempted_at);
