-- 0004_email_outbox.sql — bandeja de salida (Parte 2.1, docs/01 §6, docs/03 §3).
--
-- Patrón outbox transaccional: la fila se crea DENTRO de la transición a
-- `confirmed`, así que el correo nunca puede perderse ni duplicarse.
--   · UNIQUE (booking_id, kind) → dos confirmaciones o dos jobs simultáneos
--     chocan por unicidad: jamás hay dos correos por reserva.
--   · El contenido se renderiza al confirmar, con los datos ya congelados de la
--     reserva (mismo precio que vio el cliente en su resumen).
CREATE TABLE email_outbox (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id       integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  kind             text    NOT NULL CHECK (kind IN ('confirmation')),
  status           text    NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
  attempts         integer NOT NULL DEFAULT 0,
  next_attempt_at  timestamptz NOT NULL DEFAULT now(),
  last_error       text,
  rendered_subject text    NOT NULL,
  rendered_body    text    NOT NULL,
  sent_at          timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (booking_id, kind)
);

-- El worker consulta por (status, next_attempt_at): índice para la cola.
CREATE INDEX email_outbox_due_idx ON email_outbox (status, next_attempt_at);
