-- 0005_chat.sql — conversaciones con el asistente (Parte 2.2, docs/01 §6).
--
-- `id` es un uuid generado en la aplicación: es a la vez valor de la cookie del
-- cliente y de la cabecera `x-opencode-session` (1:1 con la conversación, lo que
-- además aprovecha el prompt caching de la API).
-- `user_id` solo se rellena si quien chatea tiene sesión iniciada; para el
-- cliente anónimo basta la cookie que transporta el `id`.
CREATE TABLE chat_sessions (
  id         text PRIMARY KEY,
  user_id    integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE chat_messages (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id  text NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
  role        text NOT NULL CHECK (role IN ('user', 'assistant')),
  content     text NOT NULL,
  action_json jsonb,                     -- acción ya validada con zod (NULL si es solo texto)
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX chat_messages_session_idx ON chat_messages (session_id, id);
