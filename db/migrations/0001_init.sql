-- 0001_init.sql — esquema inicial (docs/01 §6).
-- Instantes en timestamptz (se almacenan en UTC y se presentan en America/Bogota,
-- docs/01 §14.4). Dinero en numeric(14,2). Ids enteros (devuelve number en pg,
-- sin strings de bigint en la API).

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- viene con PostgreSQL, sin dependencias externas

CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL UNIQUE,
  full_name     text NOT NULL,
  role          text NOT NULL CHECK (role IN ('client', 'admin')),
  password_hash text NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rooms (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL UNIQUE,
  size        text NOT NULL CHECK (size IN ('small', 'medium', 'large')),
  capacity    integer NOT NULL CHECK (capacity > 0),
  hourly_rate numeric(14,2) NOT NULL CHECK (hourly_rate >= 0),
  active      boolean NOT NULL DEFAULT true
);

CREATE TABLE bookings (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name   text NOT NULL,
  customer_email  text NOT NULL,
  room_id         integer NOT NULL REFERENCES rooms(id),
  starts_at       timestamptz NOT NULL,
  ends_at         timestamptz NOT NULL,
  status          text NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'confirmed', 'completed', 'cancelled')),
  cancel_reason   text,
  -- precio PACTADO al confirmar: no se recalcula (docs/03 §2)
  total           numeric(14,2),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  confirmed_at    timestamptz,
  completed_at    timestamptz,
  CHECK (ends_at > starts_at)
);

CREATE INDEX bookings_room_id_idx ON bookings (room_id);

-- Garantía de no solape en la BASE DE DATOS, no en la app (docs/03 §1):
-- dos confirmaciones simultáneas de la misma sala y horario → la segunda
-- choca con el constraint (23P01) y la API responde 409. Solo `confirmed`
-- bloquea (enunciado literal: "no puede cruzarse con otra reserva confirmada").
-- Ojo: `starts_at`/`ends_at` son timestamptz → el rango debe ser `tstzrange`;
-- `tsrange` (timestamp sin zona) no resuelve y la migración entera falla.
ALTER TABLE bookings ADD CONSTRAINT no_room_overlap
  EXCLUDE USING btree (
    room_id  WITH =,
    tstzrange(starts_at, ends_at) WITH &&
  ) WHERE (status = 'confirmed');

CREATE TABLE booking_lines (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id integer NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  concept    text NOT NULL,
  kind       text NOT NULL CHECK (kind IN ('base', 'discount', 'surcharge', 'service')),
  amount     numeric(14,2) NOT NULL
);

CREATE INDEX booking_lines_booking_id_idx ON booking_lines (booking_id);
